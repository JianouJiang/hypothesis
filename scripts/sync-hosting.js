"use strict";
// Keep the static GitHub Pages app, local server, and hosted Worker on one engine.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const hosting = path.join(root, "hosting");
fs.mkdirSync(path.join(hosting, "lib"), { recursive: true });
fs.mkdirSync(path.join(hosting, "public"), { recursive: true });
for (const name of [
  "index.html",
  "bitcoin.html",
  "aerofoil.html",
  "aerofoil.css",
  "aerofoil.js",
  "flow-renderer.js",
  "galton.html",
  "escape.html",
  "live.html",
  "live.js",
  "live.css",
  "livestreams.js",
  "experiment.html",
  "experiment.js",
  "experiments.js",
  "experiment.css",
  "lab-renderer.js",
  "collision.js",
  "collision.css",
  "competitions.html",
  "competitions.css",
  "competitions.js",
  "profile.html",
  "home.css",
  "home.js",
  "profile.css",
  "profile.js",
  "guest.js",
  "community-ui.js",
  "community.css",
  "inbox.html",
  "inbox.js",
  "catalog.js",
  "styles.css",
  "app.js",
  "market.js",
  "favicon.svg",
  "deployment.json",
]) {
  fs.copyFileSync(path.join(root, name), path.join(hosting, "public", name));
}
fs.cpSync(
  path.join(root, "geometry"),
  path.join(hosting, "public", "geometry"),
  { recursive: true },
);
const exchange = fs
  .readFileSync(path.join(root, "exchange.js"), "utf8")
  .replace(
    'const { Market } = require("./market");',
    'import { Market } from "./engine.js";',
  )
  .replace(
    'const { CollisionMarket } = require("./collision-market");',
    'import { CollisionMarket } from "./collision-market.js";',
  )
  .replace(
    'const { LabMarket } = require("./lab-market");',
    'import { LabMarket } from "./lab-market.js";',
  )
  .replace(
    'const { randomBytes } = require("node:crypto");',
    'import { randomBytes } from "node:crypto";',
  )
  .replace(
    'const Labs = require("./experiments");',
    'import Labs from "./experiments.js";',
  )
  .replace(
    'const { LiveMarket } = require("./live-market");',
    'import { LiveMarket } from "./live-market.js";',
  )
  .replace(
    'const Live = require("./livestreams");',
    'import Live from "./livestreams.js";',
  )
  .replace(
    "module.exports = { Exchange, AeroMarket };",
    "export { Exchange, AeroMarket };",
  );
fs.writeFileSync(path.join(hosting, "lib", "exchange.js"), exchange);
for (const name of [
  "physics.js",
  "collision-market.js",
  "community.js",
  "lab-market.js",
  "lab-physics.js",
  "wave-physics.js",
  "wake-physics.js",
  "live-market.js",
  "live-feeds.js",
]) {
  let source = fs.readFileSync(path.join(root, name), "utf8");
  source = source
    .replace(
      'const Live = require("./livestreams");',
      'import Live from "./livestreams.js";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("\.\/wave-physics"\);/,
      'import $1 from "./wave-physics.js";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("\.\/wake-physics"\);/,
      'import $1 from "./wake-physics.js";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("node:crypto"\);/,
      'import $1 from "node:crypto";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("\.\/lab-physics"\);/,
      'import $1 from "./lab-physics.js";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("\.\/experiments"\);/,
      'import $1 from "./experiments.js";',
    )
    .replace(
      'const Labs = require("./experiments");',
      'import Labs from "./experiments.js";',
    )
    .replace(
      /const pl = require\("\.\/vendor\/planck.cjs"\);/,
      'import pl from "./vendor/planck.cjs";',
    )
    .replace(
      /const \{ Market \} = require\("\.\/market"\);/,
      'import { Market } from "./engine.js";',
    )
    .replace(
      /const (\{[^;]+\}) = require\("\.\/physics"\);/,
      'import $1 from "./physics.js";',
    )
    .replace(/module\.exports\s*=\s*(\{[^;]+\});/, "export $1;");
  fs.writeFileSync(path.join(hosting, "lib", name), source);
}
fs.mkdirSync(path.join(hosting, "lib", "vendor"), { recursive: true });
for (const file of ["planck.cjs", "PLANCK-LICENSE.txt"])
  fs.copyFileSync(
    path.join(root, "vendor", file),
    path.join(hosting, "lib", "vendor", file),
  );
fs.copyFileSync(
  path.join(root, "index.html"),
  path.join(hosting, "lib", "home.html"),
);
fs.copyFileSync(
  path.join(root, "bitcoin.html"),
  path.join(hosting, "lib", "market.html"),
);
const source = fs.readFileSync(path.join(root, "market.js"), "utf8");
const bodyStart = source.search(/["']use strict["'];/);
const bodyEnd = source.lastIndexOf("\n});");
if (bodyStart < 0 || bodyEnd < bodyStart) {
  throw new Error(
    "Cannot locate the shared engine factory. Check market.js before publishing.",
  );
}
const body = source.slice(bodyStart, bodyEnd);
fs.writeFileSync(
  path.join(hosting, "lib", "engine.js"),
  "// Generated by scripts/sync-hosting.js; edit the root market.js.\nexport const { Market, ROUND_MS, floorShares } = (() => {\n" +
    body +
    "\n})();\n",
);
console.log("Hosted HTML, assets, and trading engine synchronized.");

// Convert the public UMD definitions to a single ESM instance for Worker imports.
const labSource = fs.readFileSync(path.join(root, "experiments.js"), "utf8");
const labStart = labSource.indexOf("const definitions"),
  labEnd = labSource.lastIndexOf("return {");
if (labStart < 0 || labEnd < labStart)
  throw new Error("Cannot locate experiment definitions factory.");
fs.writeFileSync(
  path.join(hosting, "lib", "experiments.js"),
  labSource.slice(labStart, labEnd).trimEnd() +
    "\nconst Labs={definitions,ids,parse,contractIds,label,link};\nexport {definitions,ids,parse,contractIds,label,link};\nexport default Labs;\n",
);

// Public live-stream definitions share one ESM instance with the Worker engine.
const liveSource = fs.readFileSync(path.join(root, "livestreams.js"), "utf8");
const liveStart = liveSource.indexOf("const HST"),
  liveEnd = liveSource.lastIndexOf("return {");
if (liveStart < 0 || liveEnd < liveStart)
  throw new Error("Cannot locate live-stream definitions factory.");
fs.writeFileSync(
  path.join(hosting, "lib", "livestreams.js"),
  liveSource.slice(liveStart, liveEnd).trimEnd() +
    "\nconst Live={definitions,ids,parse,label,link,deadline,question,embedUrl};\nexport {definitions,ids,parse,label,link,deadline,question,embedUrl};\nexport default Live;\n",
);
